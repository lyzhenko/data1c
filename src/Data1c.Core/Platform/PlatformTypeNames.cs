using System.Collections.Frozen;

namespace Data1c.Core.Platform;

/// <summary>
/// Имена типов платформы 1С, которые библиотека знает без синтакс-помощника. Нужны там, где
/// установленной платформы под рукой нет, а тип переменной известен из кода: если переменная имеет
/// такой тип, вызов «Переменная.Метод» считается методом платформы, а не внешней заглушкой.
/// </summary>
/// <remarks>
/// Список намеренно короткий и состоит из типов, которые в коде встречаются постоянно. Когда
/// подключена справка платформы (<c>--platform</c>), проверка идёт по ней
/// (<see cref="PlatformHelpIndex.IsKnownType"/>), и список служит дополнением, а не заменой.
/// </remarks>
public static class PlatformTypeNames
{
    /// <summary>Часто встречающиеся типы платформы. Сравнение — без учёта регистра.</summary>
    public static FrozenSet<string> Common { get; } = new HashSet<string>(StringComparer.OrdinalIgnoreCase)
    {
        // Коллекции и значения.
        "Массив", "ФиксированныйМассив", "Структура", "ФиксированнаяСтруктура",
        "Соответствие", "ФиксированноеСоответствие", "СписокЗначений", "КлючИЗначение",
        "ТаблицаЗначений", "ДеревоЗначений", "ТабличныйДокумент",
        "ХранилищеЗначения", "ДвоичныеДанные", "УникальныйИдентификатор", "ОписаниеТипов",
        "Картинка", "Диаграмма", "ГрафическаяСхема", "ГеографическаяСхема",
        "ФорматированнаяСтрока",

        // Примитивные типы.
        "Строка", "Число", "Дата", "Булево", "Неопределено", "Null", "Тип",

        // Запросы и обмен.
        "Запрос", "ПостроительЗапроса", "СхемаКомпоновкиДанных",
        "ЧтениеXML", "ЗаписьXML", "ЧтениеJSON", "ЗаписьJSON", "ЧтениеТекста", "ЗаписьТекста",
        "Поток", "ПотокВПамяти", "Файл", "ФайловыйПоток", "ПочтовыйПрофиль", "ИнтернетПочтовоеСообщение",
        "HTTPСоединение", "HTTPЗапрос", "HTTPОтвет", "HTTPСервисОтвет", "HTTPСервисЗапрос",
        "FTPСоединение", "COMОбъект", "WSСсылка", "WSОпределения", "WSПрокси",
        "СистемнаяИнформация", "СериализаторXDTO",

        // Формы и интерфейс.
        "ДинамическийСписок", "Форма", "ФормаКлиентскогоПриложения", "УправляемаяФорма",
        "ЭлементыФормы", "РасширениеУправляемойФормы", "ПолеФормы", "ТаблицаФормы",
        "ЗаписьЖурналаРегистрации", "ГруппировкаТаблицыЗначений", "СтрокаТаблицыЗначений",
        "КолонкаТаблицыЗначений", "СтрокаДереваЗначений", "КолонкаДереваЗначений",
    }.ToFrozenSet(StringComparer.OrdinalIgnoreCase);

    /// <summary>Известен ли такой тип платформы без обращения к справке.</summary>
    public static bool IsKnown(string? name) => !string.IsNullOrWhiteSpace(name) && Common.Contains(name.Trim());

    /// <summary>
    /// Имя похоже на имя типа: буквы, цифры, «_» и точки (например, «СправочникОбъект.Товары»),
    /// без пробелов и разделителей списка типов.
    /// </summary>
    public static bool LooksLikeTypeName(string? name)
    {
        if (string.IsNullOrWhiteSpace(name))
        {
            return false;
        }

        var text = name.Trim();
        for (var i = 0; i < text.Length; i++)
        {
            var c = text[i];
            if (i == 0)
            {
                if (!char.IsLetter(c) && c != '_')
                {
                    return false;
                }

                continue;
            }

            if (!char.IsLetterOrDigit(c) && c != '_' && c != '.')
            {
                return false;
            }
        }

        return true;
    }
}
